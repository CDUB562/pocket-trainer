// Writes ios/PocketTrainer/Catalog.swift from SKILLS in src/catalog.js, so the web and iPhone apps teach the same steps.
// The iPhone app is still on v1 (one dog, step ladders only), so only the 10 original skills go across until it gets the v2 engine.
// Run: node tools/gen_catalog.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const V1 = ["name", "touch", "sit", "down", "stay", "come", "leave", "drop", "leash", "mat"];
const src = fs.readFileSync(path.join(root, "src/catalog.js"), "utf8");
const M = new Function(src + "; return SKILLS;")().filter((m) => V1.includes(m.id));
const q = (x) => JSON.stringify(x); // JSON string escaping is valid Swift for this text

let o = `// Generated by tools/gen_catalog.js from src/catalog.js. Edit the catalog there, then rerun.
// hold: the step gets a hold timer that marks Yes at a random moment in that range (seconds).
// keep: the Keep going marker shows on this step (holds always get it).

enum Catalog {
    static let modules: [Module] = [
`;
for (const m of M) {
  o += `        Module(id: ${q(m.id)}, name: ${q(m.name)}, goal: ${q(m.goal)}, cue: ${q(m.cue)}, steps: [\n`;
  for (const t of m.steps) {
    o += `            Step(title: ${q(t.t)}, mark: ${q(t.mark)}, setup: ${q(t.setup)}, reward: ${q(t.reward)}`
      + (t.hold ? `, hold: ${t.hold[0]}...${t.hold[1]}` : "") + (t.keep ? ", keep: true" : "") + "),\n";
  }
  o += "        ]),\n";
}
o += `    ]

    static let free = Module(id: "free", name: "Free clicker", goal: "Just the marker pad, no plan.", cue: "", steps: [])

    /// The order new skills are introduced on Today.
    static let order = ["name", "touch", "sit", "down", "come", "leave", "mat", "stay", "drop", "leash"]

    static func module(_ id: String) -> Module { modules.first { $0.id == id } ?? free }
    static func isSkill(_ id: String) -> Bool { modules.contains { $0.id == id } }
}
`;
fs.writeFileSync(path.join(root, "ios/PocketTrainer/Catalog.swift"), o);
console.log(`${M.length} skills, ${M.reduce((n, m) => n + m.steps.length, 0)} steps`);
